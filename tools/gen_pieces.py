#!/usr/bin/env python3
"""Turn Lichess's cburnett SVG pieces (tools/cburnett, GPLv2+ by Colin M.L. Burnett) into Pieces.kt."""
import xml.etree.ElementTree as ET
from pathlib import Path

here = Path(__file__).parent
NS = "{http://www.w3.org/2000/svg}"
KEYS = ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "fill-rule")


def color(v):
    if v in (None, "none"):
        return "null"
    v = v.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    return f"0xFF{v.upper()}"


def walk(el, inherited, out):
    attrs = dict(inherited)
    for k in KEYS:
        if k in el.attrib:
            attrs[k] = el.attrib[k]
    tag = el.tag.replace(NS, "")
    d = None
    if tag == "path":
        d = el.attrib["d"]
    elif tag == "circle":
        cx, cy, r = (float(el.attrib[k]) for k in ("cx", "cy", "r"))
        d = f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0z"
    if d:
        out.append((d, attrs))
    for c in el:
        walk(c, attrs, out)


lines = [
    "// Generated by tools/gen_pieces.py from Lichess's cburnett set (Colin M.L. Burnett, GPLv2+). Do not edit.",
    "package com.rusty.gambit", "",
    "internal val PIECE_PARTS: Map<String, List<PiecePart>> = mapOf(",
]
for f in sorted((here / "cburnett").glob("*.svg")):
    parts = []
    walk(ET.parse(f).getroot(), {"fill": "#000"}, parts)
    lines.append(f'    "{f.stem}" to listOf(')
    for d, a in parts:
        lines.append(
            f'        PiecePart("{d}", {color(a.get("fill"))}, {color(a.get("stroke"))}, '
            f'{float(a.get("stroke-width", 1))}f, "{a.get("stroke-linecap", "butt")}", '
            f'"{a.get("stroke-linejoin", "miter")}", {str(a.get("fill-rule") == "evenodd").lower()}),')
    lines.append("    ),")
lines.append(")")
(here.parent / "app/src/main/java/com/rusty/gambit/Pieces.kt").write_text("\n".join(lines) + "\n")
print("wrote", sum(1 for l in lines if "PiecePart(" in l), "parts")
